"""HTML experiment report generation."""

from html import escape
from pathlib import Path


def write_report(results, path):
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    table = results.leaderboard.to_html(index=False, escape=True, border=0, classes="leaderboard")
    metrics = "".join(
        f"<tr><th>{escape(str(name))}</th><td>{escape(str(value))}</td></tr>"
        for name, value in results.metrics.items()
    )
    config = "".join(
        f"<tr><th>{escape(str(name))}</th><td>{escape(str(value))}</td></tr>"
        for name, value in results.experiment.items()
    )
    note = escape(results.selection_note)
    html = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width">
<title>AutoDataMining report</title>
<style>body{{font:16px/1.5 system-ui,sans-serif;max-width:1100px;margin:2rem auto;padding:0 1rem;color:#202124}}
table{{border-collapse:collapse;width:100%;margin:1rem 0}}th,td{{border:1px solid #ddd;padding:.5rem;text-align:left}}
th{{background:#f2f4f8}}.notice{{background:#fff7df;padding:1rem;border-left:4px solid #d69e00}}</style></head>
<body><h1>AutoDataMining experiment report</h1><p>Task: <strong>{escape(results.task)}</strong>; selected model:
<strong>{escape(str(results.model_name))}</strong></p><p class="notice">{note}<br>Scores describe this experiment only;
they do not guarantee performance on future data. Feature importance is not causal evidence. The report
contains experiment metadata, not dataset rows.</p><h2>Selected model metrics</h2><table>{metrics}</table>
<h2>Leaderboard</h2>{table}<h2>Experiment configuration</h2><table>{config}</table>
<footer>Generated by AutoDataMining. Review split design, data quality, and metric suitability before use.</footer>
</body></html>"""
    destination.write_text(html, encoding="utf-8")
    return destination
